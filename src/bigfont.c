static const glyph *find_glyph(char c)
{
    int i;
    if (c != 't' && c != 'y' && c >= 'a' && c <= 'z')
        c = (char)(c - 32);
    for (i = 0; i < ARRAY_LEN(GLYPHS); i++)
        if (GLYPHS[i].ch == c)
            return &GLYPHS[i];
    return NULL;
}

int bigfont_width(const char *text)
{
    int n = (int)strlen(text);
    return n > 0 ? n * BIGFONT_ADVANCE - 1 : 0;
}

int bigfont_draw(int x, int y, const char *text, uint32_t fg, uint32_t bg)
{
    int x0 = x;
    for (; *text; text++, x += BIGFONT_ADVANCE) {
        const glyph *g = find_glyph(*text);
        int row, col;
        if (!g)
            g = find_glyph('*');
        for (row = 0; row < BIGFONT_ROWS; row++) {
            for (col = 0; col < 5; col++) {
                int top = g->rows[row * 2][col] == '#';
                int bot = row * 2 + 1 < 7 && g->rows[row * 2 + 1][col] == '#';
                uint32_t ch = top && bot ? 0x2588 : top ? 0x2580 : bot ? 0x2584 : ' ';
                if (ch == ' ') {
                    if (bg != COLOR_KEEP)
                        scr_put(x + col, y + row, ' ', fg, bg, 0);
                } else {
                    scr_put(x + col, y + row, ch, fg, bg, 0);
                }
            }
        }
    }
    return x - x0 > 0 ? x - x0 - 1 : 0;
}
